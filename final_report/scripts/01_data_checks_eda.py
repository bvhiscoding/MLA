# E6d unit-level association tests (chi-square, Cramer's V) and essay-level Spearman
def cramers_v(a, b):
    ct = pd.crosstab(a, b)
    chi2 = stats.chi2_contingency(ct)[0]
    return chi2, np.sqrt(chi2 / (ct.values.sum() * (min(ct.shape) - 1)))


